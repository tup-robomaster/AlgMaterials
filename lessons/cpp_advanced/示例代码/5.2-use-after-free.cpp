// 5.2 例题：释放之后，又用同一个地址读了一次。
//
// 这一份最难查：它不崩溃、不报错，直接给出一个数——可那个数无效。
// 那块内存已经释放，从那一刻起它归别的代码管理、里面是什么也无法确定；
// 这次读到的和上次写进去的常常对不上，而且每次运行都可能不一样。
// 「没有崩溃」不等于「这次是正确的」。这类行为有一个名字：未定义行为
// （undefined behavior）——标准对它会产生什么结果不作任何保证。
//
// 编译并运行：g++ -std=c++17 -Wall 示例代码/5.2-use-after-free.cpp -o /tmp/t && /tmp/t

#include <iostream>

int main() {
    int* p = new int;
    *p = 7;
    std::cout << "写进去的是 " << *p << std::endl;

    delete p;       // 释放完成，从这一刻起 p 是悬空指针

    std::cout << "释放之后又读了一次，读到 " << *p << std::endl;
    std::cout << "——这个数无效：再运行一次，可能就是另一个数。" << std::endl;

    p = nullptr;    // 能做的一件正事：把指针置成空，防止下次再拿它去读写
    return 0;
}
