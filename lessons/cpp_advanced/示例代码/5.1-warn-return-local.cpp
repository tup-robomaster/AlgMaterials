// 5.1 警告例：把栈上变量的地址传出去。
//
// pick 一返回，它所在的函数作用域就结束了，local 那个变量随之销毁。
// 传出去的地址指向的是一块已经销毁的内存——编译器看得出来，
// 在编译那一步就警告你。这一份能编译通过（是警告不是报错），运行起来也不崩溃，
// 因此最容易被忽略。
//
// 这一份不去访问这个地址（访问会怎样，5.2 专门讲），只看它是什么：
// 这份编译器直接给出一个空地址——换台机器、换个编译器，也可能是别的结果。
// 哪一种都无效。
//
// 编译：g++ -std=c++17 -Wall 示例代码/5.1-warn-return-local.cpp -o /tmp/t

#include <iostream>

int* pick() {
    int local = 7;
    return &local;      // 传出去的是地址，可那块内存马上要销毁
}

int main() {
    int* p = pick();

    if (p == nullptr) {
        std::cout << "取得的地址是空的。" << std::endl;
    } else {
        std::cout << "取得一个看上去正常的地址：" << p << std::endl;
    }
    std::cout << "（那块内存已经销毁——不管得到什么地址，都无效）" << std::endl;

    return 0;
}
