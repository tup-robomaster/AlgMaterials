def det2(M):
    return M[0][0] * M[1][1] - M[0][1] * M[1][0]


def det3(M):
    a, b, c = M[0]
    m1 = [[M[1][1], M[1][2]], [M[2][1], M[2][2]]]
    m2 = [[M[1][0], M[1][2]], [M[2][0], M[2][2]]]
    m3 = [[M[1][0], M[1][1]], [M[2][0], M[2][1]]]
    return a * det2(m1) - b * det2(m2) + c * det2(m3)


def num(x):
    if abs(x - round(x)) < 1e-9:
        return str(int(round(x)))
    return '%.3f' % x


A2 = [[2.0, 1.0], [1.0, 3.0]]
A3 = [[2.0, 1.0, 0.0], [1.0, 3.0, 1.0], [0.0, 1.0, 2.0]]
p, q, r = (0.0, 0.0), (4.0, 0.0), (0.0, 3.0)
area = abs((q[0] - p[0]) * (r[1] - p[1]) -
           (q[1] - p[1]) * (r[0] - p[0])) / 2

print('2×2 行列式 = ' + num(det2(A2)))
print('3×3 行列式 = ' + num(det3(A3)))
print('三角形面积 = %.3f' % area)
