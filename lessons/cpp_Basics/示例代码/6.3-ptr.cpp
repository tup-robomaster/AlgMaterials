// 6.3 指针：盒子里装的不是数，是另一个盒子的门牌号
//
//   p      装的是地址（a 住在哪儿）
//   *p     顺着这个地址找过去，看到的就是 a 本人
//
// 所以 *p = 9; 改的就是 a。这跟 6.2 的引用是一回事，
// 只是引用是编译器替你保管地址，指针是你自己拿着。

#include <iostream>

int main() {
    int a = 3;

    int* p = &a;    // p 这个盒子，装的是 a 的地址

    std::cout << "*p = " << *p << std::endl;   // 顺着地址找过去

    *p = 9;                                    // 顺着地址找过去，写进去

    std::cout << "a = " << a << std::endl;
    std::cout << "p 里装的就是 a 的地址吗  " << (p == &a) << std::endl;

    return 0;
}
