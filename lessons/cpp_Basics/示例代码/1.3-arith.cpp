// 1.3 运算：加减乘除、取余
//
// 五个运算符各来一次，先自己猜结果，再跑。

#include <iostream>

int main() {
    int a = 7;
    int b = 2;

    std::cout << a + b << std::endl;   // 加
    std::cout << a - b << std::endl;   // 减
    std::cout << a * b << std::endl;   // 乘
    std::cout << a / b << std::endl;   // 除
    std::cout << a % b << std::endl;   // 取余

    return 0;
}
