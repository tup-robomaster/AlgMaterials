// 2.1：不加大括号会怎样。
//
// 58 分没到 60，但「恭喜」还是打出来了——因为它不在 if 里面。
//
// 关键在第二句的缩进：写的人以为它归 if 管，手也就这么缩进去了。
// C++ 只认语法，不认缩进——多缩的那一格，是写的人自己骗自己。
//
// 这份文件故意写成这样，所以名字里带 warn：加 -Wall 编译，它会报一条
// -Wmisleading-indentation，说「这个 if 不管着这一句」。
// 学生从 0.1 起就一直带着 -Wall，所以他们屏幕上看到的和这里跑出来的一样。
// 课里那一段把这条警告原样贴出来了——它正好用来说明
// 「警告拦不住程序」：编译照样过，跑起来照样打「恭喜」。

#include <iostream>

int main() {
    int score = 58;

    if (score >= 60)
        std::cout << "及格" << std::endl;
        std::cout << "恭喜" << std::endl;

    return 0;
}
