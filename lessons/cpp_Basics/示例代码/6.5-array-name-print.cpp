// 6.5 数组名直接丢给 cout，打出来的是什么
//
// 两个都是「一串东西的开头」，可打出来完全不一样：
//   int  数组 —— 打的是一个地址
//   char 数组 —— 打的是那一串字本身
//
// 因为 cout 是看**类型**决定怎么打的：char* 它就当字符串，
// 一路打到结尾记号为止；别的指针就当地址打。
// 1.x 说过「同一份数据，用什么身份去看，就打出来什么样子」——这就是那一句。

#include <iostream>

int main() {
    int  a[3] = {10, 20, 30};
    char c[4] = "abc";

    std::cout << a << std::endl;
    std::cout << c << std::endl;

    return 0;
}
