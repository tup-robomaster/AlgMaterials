// 4.2：用循环把数组挨个走一遍。
//
// 这一步把数组的两半拼起来了：第 2 部分的 for，和第 4.1 的编号。
// 循环变量 i 从 0 走到 4，正好就是所有合法的编号——
// 一个不多，一个不少。
//
// 注意条件里那个 5 是**个数**，所以是 i < 5，不是 i <= 5。
// 这里差一个字符，就是这一课后半截要讲的事。

#include <iostream>

int main() {
    int score[5] = {90, 85, 77, 60, 95};

    for (int i = 0; i < 5; i++) {
        std::cout << score[i] << std::endl;
    }

    return 0;
}
