// 2.6 例题：9×9 乘法表（for 版）。
//
// 骨架和 2.5 的直角三角形一模一样：外圈管行，内圈管这一行打几个。
// 换掉的只有两处：
//   1. 内圈打的不是星号，是一个算式；
//   2. 算式用 printf 打，乘法结果占两格（%2d），列才对得齐。
//
// 为什么是 %2d：积最大到 81，两位。让它至少占两格，
// 每一个格子的长度就都一样了——不管是一位数还是两位数。
//
// 跑一下：g++ -std=c++17 -Wall 示例代码/2.6-example.cpp -o /tmp/t && /tmp/t

#include <cstdio>

int main() {
    for (int i = 1; i <= 9; i = i + 1) {
        for (int j = 1; j <= i; j = j + 1) {
            printf("%d×%d=%2d ", j, i, i * j);
        }
        printf("\n");
    }

    return 0;
}
