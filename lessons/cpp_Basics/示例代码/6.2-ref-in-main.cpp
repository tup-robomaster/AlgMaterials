// 6.2：引用不只写在参数表上
//
// 3.5 见的那些 & 都长在函数参数表里，容易留下一个错觉，
// 以为引用是参数表专用的东西。这一份把 & 挪到 main 里，
// 参数表上那个 int& x 和这里的 int& r 是同一个东西，一个字都没变。
//
// 换到 main 里站，要多守三条规矩，那是 6.2 后面讲的。

#include <iostream>

int main() {
    int a = 1;
    int& r = a;      // 可以在这儿写，不用非在函数参数里

    r = 9;           // 改 r，就是改 a

    std::cout << a << std::endl;
    return 0;
}
