// 练习 7-14：打的是 18。
//
// 读法：条件里那个 i % 2 == 0 看的是「编号是不是偶数」，不是「值是不是偶数」。
// 所以加进去的是编号 0、2、4 三个格子：2 + 6 + 10 = 18。
// 加一句打印，把每一轮的 i 和 s 都打出来，一眼就看清它跳过的是哪几个。

#include <iostream>

int main() {
    int a[6] = {2, 4, 6, 8, 10, 12};
    int s = 0;

    for (int i = 0; i < 6; i++) {
        if (i % 2 == 0) {
            s = s + a[i];
        }
        std::cout << "i = " << i << " 时，s = " << s << std::endl;
    }

    std::cout << s << std::endl;

    return 0;
}
