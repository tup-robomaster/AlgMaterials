// 练习 6-2 的答案：三样都打出来
//
// 第三个 12 是 3 个 int、每个 4 格。前两个是 1，说明：
// 数组名就是首元素的地址；越靠后的元素地址越大（它们是挨着放的）。

#include <iostream>

int main() {
    int a[3] = {10, 20, 30};

    std::cout << (a == &a[0])    << " "
              << (&a[2] > &a[0]) << " "
              << sizeof(a)       << std::endl;

    return 0;
}
