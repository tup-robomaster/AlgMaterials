// 4.2：下标走出去了，编译器一声不吭。
//
// score 只有 5 个盒子，编号 0 到 4。这里递进去的是 5——
// 第 6 个，不存在。
//
// 重点不是它打出来什么，是**它什么都没说**：编译干净，
// 跑起来也正常收场，屏幕上出现了一个数。

#include <iostream>

int main() {
    int score[5] = {90, 85, 77, 60, 95};

    int i = 5;                          // 循环多转了一圈，i 就到了 5

    std::cout << score[i] << std::endl;

    return 0;
}
