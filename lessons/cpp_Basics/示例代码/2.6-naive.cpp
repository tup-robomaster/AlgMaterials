// 这文件里是**没有对齐**的那一版，专门留着跟 2.6-example.cpp 对比用的。
// 它和 2.5 那个直角三角形是同一个骨架，只是把星号换成了算式。
//
// 乘号打的也是 ×、间隔也是一个空格——跟正解只差「有没有把宽度定死」
// 这一件事，这样两份摆在一起，漂移就只可能是那一个原因造成的。
//
// 跑一下：g++ -std=c++17 -Wall 示例代码/2.6-naive.cpp -o /tmp/t && /tmp/t
// 数一数第 3 列在第 3 行和第 5 行是不是从同一个位置开始的。

#include <iostream>

int main() {
    for (int i = 1; i <= 9; i = i + 1) {
        for (int j = 1; j <= i; j = j + 1) {
            std::cout << j << "×" << i << "=" << i * j << " ";
        }
        std::cout << std::endl;
    }

    return 0;
}
