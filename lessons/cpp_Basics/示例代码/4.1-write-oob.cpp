// 4.1 数组 —— 补充：往第六个盒子里塞东西
//
// 这份程序编译干净、跑起来退出码 0、屏幕上什么异常都没有。
// 但它干的事是错的：score[5] 这个位置根本不属于这个数组。
//
// 这就是最危险的一种——不留痕迹。

#include <iostream>

int main() {
    int score[5] = {90, 85, 77, 60, 95};

    score[5] = 88;                    // 想塞第六个

    std::cout << "第一个 " << score[0] << std::endl;

    return 0;
}
