// 4.2 遍历数组 —— 补充：同一个 <= 落在「写」的那一边
//
// 编译干净、一个警告都没有，跑出来的五个数一个不多一个不少。
// 看着全对。
//
// 可那个填值的循环最后一圈 i 是 5，执行的其实是 score[5] = 65，
// 写到了数组外面。这一行屏幕上一点痕迹都没留下。

#include <iostream>

int main() {
    int score[5] = {0, 0, 0, 0, 0};

    for (int i = 0; i <= 5; i++) {
        score[i] = 60 + i;      // i 走到 5 的那一圈，写到数组外面去了
    }

    for (int i = 0; i < 5; i++) {
        std::cout << score[i] << std::endl;
    }

    return 0;
}
