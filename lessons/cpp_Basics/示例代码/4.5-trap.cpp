// 4.5：题目里那个陷阱。
//
// 这份是**错的**：它把输入开头的那个 5 也当成了数据。
//
// 为什么会有人这么写：拿到样例行「5 4 9 1 7 3」，
// 一眼看过去是「6 个数」，于是照着 6 写了个循环，
// 把整行都读进数组。跑出来是一排数，看着挺像回事——
// 其实就是正确输出前面多贴了一个 5：那个 5 从头到尾
// 坐在第一个格子里没动过，哪一次交换都轮不到它。
//
// 病根不在这个 6，在**「数出来的个数」**这件事本身：
// 换一组输入，个数就变了，而你写死的那份不会变。
// 题目把个数摆在开头，就是让你别去数——让程序去读。
//
// 打印那一段跟正解一样写两遍（交换前后各一行），
// 这样两份程序摆在一起，差别就只剩那个数错的 6。
//
// 输入和正解共用一份：4.5-trap.in

#include <iostream>

int main() {
    int a[100];

    for (int i = 0; i < 6; i++) {
        std::cin >> a[i];
    }

    int minIdx = 0;
    for (int i = 1; i < 6; i++) {
        if (a[i] < a[minIdx]) {
            minIdx = i;
        }
    }

    // 交换前
    std::cout << a[0];
    for (int i = 1; i < 6; i++) {
        std::cout << " " << a[i];
    }
    std::cout << std::endl;

    int t = a[minIdx];
    a[minIdx] = a[5];
    a[5] = t;

    // 交换后
    std::cout << a[0];
    for (int i = 1; i < 6; i++) {
        std::cout << " " << a[i];
    }
    std::cout << std::endl;

    return 0;
}
