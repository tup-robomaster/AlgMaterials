// 6.3 没初始化的指针里是什么
//
// 答案：是内存里剩下的旧数据，**不是 0**。基本类型没有构造函数，
// 没人管它（5.3 讲过 int score 为什么不干净，指针是一回事）。
//
// 更麻烦的是：读一个没初始化的指针本身就是「没定义的行为」，
// 编译器爱怎么处理就怎么处理。所以同一份代码：
//
//     g++ -std=c++17 -Wall 6.3-ptr-uninit.cpp -o t     →  打 0
//     g++ -std=c++17 -Wall -O2 6.3-ptr-uninit.cpp -o t →  打 1
//
// 两个结果都出现过，都不是「保证」。所以**别赌**：指针一开出来就写
// = nullptr 或者 = &某个变量。

#include <iostream>

int main() {
    int* p;          // 没初始化

    std::cout << "它等于空指针吗  " << (p == nullptr) << std::endl;

    return 0;
}
