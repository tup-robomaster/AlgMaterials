// 4.4：想把两个盒子换过来，直接互相赋值。
//
// 这份是**错的**，而且错得很有代表性：两行都执行了，一行没漏，
// 编译干净、跑起来正常——结果两个盒子装的是同一个数。
//
// 盯着第一行看：a[0] = a[1] 之后，a[0] 里那个 1 就已经没了。
// 第二行再拿 a[0] 去填 a[1]，填进去的是刚写下去的 2。
// 你想让 1 走一趟，可它在中途就被盖掉了。

#include <iostream>

int main() {
    int a[2] = {1, 2};

    a[0] = a[1];
    a[1] = a[0];

    std::cout << a[0] << " " << a[1] << std::endl;

    return 0;
}
