// 4.2 例题：一组成绩，数一数有几个不及格。
//
// 那个记数的盒子 fail 开在循环**外面**——理由和 sum 一样：
// 每一圈都得留着。开在里面的话，每转一圈就清零，
// 最后不管有几个不及格，打出来的都是最后一个。
//
// 注意打出来的两个数不是一回事：「第 1 个／第 3 个」里的 1 和 3 是
// 盒子的**编号**（i），最后那行「一共 2 个」的 2 是**碰到的次数**（fail）。
// 编号可以不连着，次数一定连着。

#include <iostream>

int main() {
    int score[6] = {90, 55, 77, 48, 60, 95};

    int fail = 0;

    for (int i = 0; i < 6; i++) {
        if (score[i] < 60) {
            std::cout << "第 " << i << " 个不及格：" << score[i] << std::endl;
            fail = fail + 1;
        }
    }

    std::cout << "一共 " << fail << " 个" << std::endl;

    return 0;
}
