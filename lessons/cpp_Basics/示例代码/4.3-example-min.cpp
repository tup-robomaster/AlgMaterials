// 4.3 例题：找最小的那个，并说出它在第几个。
//
// 和 4.3-maxidx.cpp 是一个模子，只把 > 换成了 <。
//
// 数组里有两个 3（第 1 个和第 3 个）。打出来的是**第 1 个**——
// 因为条件是严格的 <：第 3 个那个 3 不比台上的 3 更小，
// 所以它上不去。想留最后一个，把 < 改成 <= 就行。
// 这种「并列的时候要哪个」的事，题目不说清楚就得自己先定下来。

#include <iostream>

int main() {
    int a[6] = {7, 3, 9, 3, 8, 4};

    int minIdx = 0;

    for (int i = 1; i < 6; i++) {
        if (a[i] < a[minIdx]) {
            minIdx = i;
        }
    }

    std::cout << "最小的是 " << a[minIdx] << "，在第 " << minIdx << " 个" << std::endl;

    return 0;
}
