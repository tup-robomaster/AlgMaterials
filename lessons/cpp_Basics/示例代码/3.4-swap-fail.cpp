// 3.4：一个看起来该成、其实不成的程序。
//
// 想把 a 和 b 换过来。函数里明明换了，打出来还是 1 2，一动没动。
// 编译器一声不吭——这不是语法错，是**想法**错了。
//
// 每一步干了什么，下面注释里写得清清楚楚；你先别急着往下翻，
// 自己盯一会儿：这两个数是在哪一步「换回来」的。

#include <iostream>

// 交换两个数——函数里确实换成了
void swapTwo(int x, int y) {
    int t = x;      // t 拿到 x 的值，现在是 1
    x = y;          // x 变成 2
    y = t;          // y 变回 1
}                   // 到这里，x 是 2、y 是 1，看起来换好了

int main() {
    int a = 1;
    int b = 2;

    swapTwo(a, b);

    std::cout << a << " " << b << std::endl;
    return 0;
}
