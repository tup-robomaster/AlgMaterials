// 4.4 例题：把第一个和最后一个换过来。
//
// 和 4.4-swap.cpp 是同一件事，只是编号从 0、1 换成了 0、4。
// 数组有几个元素，最后一个的编号就是几减一——这一课里
// 5 个元素，最后一个的编号是 4。
//
// 中间那三个数睡着了：打的还是原来的位置，谁也没动它们。

#include <iostream>

int main() {
    int a[5] = {10, 20, 30, 40, 50};

    int t = a[0];
    a[0] = a[4];
    a[4] = t;

    std::cout << a[0];
    for (int i = 1; i < 5; i++) {
        std::cout << " " << a[i];
    }
    std::cout << std::endl;

    return 0;
}
