// 4.2：想让上面那份程序把五个成绩都打出来，条件却写成了 i <= 5。
//
// 这份是**错的**，但它是那种最坏的错：编译干净、一个警告都没有、
// 跑起来也正常收场。它只是多走了一圈，把第 6 个盒子里的东西
// 也打了出来——而第 6 个盒子根本不存在。
//
// 多打出来的那个数每次都不一样。这不是「随机数」，是那块内存里
// 当时恰好放着的东西，跟你之前跑过什么、系统忙不忙都有关系。
//
// 它和练习 4-6 是一对：那边是找错，这边是错的样子。

#include <iostream>

int main() {
    int score[5] = {90, 85, 77, 60, 95};

    for (int i = 0; i <= 5; i++) {
        std::cout << score[i] << std::endl;
    }

    return 0;
}
